export function translate(
  text: string,
  language: AppLanguage,
  values: Record<string, string | number> = {}
): string {
  if (language !== 'km') return text;
  const exact = khmerTranslations[text];
  const translated = exact ?? text;
  return translated.replace(/\{([^}]+)\}/g, (placeholder, key: string) =>
    String(values[key] ?? placeholder)
  );
}
